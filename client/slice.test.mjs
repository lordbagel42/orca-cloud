import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { slice } from "./slice.mjs";

async function fixture(t) {
  const dir = await mkdtemp(join(tmpdir(), "orca-client-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const inputPath = join(dir, "model.stl");
  const outputPath = join(dir, "output.gcode");
  const tokenFile = join(dir, "key");
  await writeFile(inputPath, "solid test\nendsolid test\n");
  await writeFile(tokenFile, "test-key\n");
  return { inputPath, outputPath, tokenFile };
}

test("rejects unknown options instead of silently using the fixed preset", async (t) => {
  const paths = await fixture(t);
  const fetchMock = t.mock.method(globalThis, "fetch", () => {
    throw new Error("No request should occur for unknown options");
  });
  for (const key of [
    "configuration",
    "configurationID",
    "nozzle_diameter",
    "perset",
  ]) {
    await assert.rejects(
      slice({ ...paths, [key]: "unexpected" }),
      /Unknown slice options/,
    );
  }
  assert.equal(fetchMock.mock.callCount(), 0);
});

test("uploads the model, polls the job, and saves G-code instead of following response URLs", async (t) => {
  const paths = await fixture(t);
  const gcode = "; generated by OrcaSlicer\nG1 X12 Y7 E0.4\n";
  const states = [];
  t.mock.method(globalThis, "fetch", async (url, options) => {
    assert.equal(url.origin, "https://orca.bagelindustries.com");
    assert.equal(options.headers.Authorization, "Bearer test-key");
    assert.equal(options.redirect, "manual");
    if (options.method === "POST") {
      assert.equal(url.searchParams.get("preset"), "bambu-a1-mini-0.4-pla");
      assert.equal(options.headers["Content-Type"], "model/stl");
      assert.deepEqual(options.body, await readFile(paths.inputPath));
      return Response.json(
        {
          id: "job-123",
          status: "queued",
          status_url: "https://wrong.invalid/",
        },
        { status: 202 },
      );
    }
    if (url.pathname === "/v1/jobs/job-123") {
      return Response.json({
        status: "succeeded",
        output_url: "https://wrong.invalid/",
        output_bytes: 41,
        output_sha256:
          "f1b60c6f4da626ef59157bf734473123e11604035a38af841db6cf5984f36205",
      });
    }
    assert.equal(url.pathname, "/v1/jobs/job-123/gcode");
    let chunk = 0;
    return new Response(
      new ReadableStream({
        async pull(controller) {
          await assert.rejects(readFile(paths.outputPath), { code: "ENOENT" });
          controller.enqueue(
            new TextEncoder().encode(
              chunk++ === 0 ? gcode.slice(0, 10) : gcode.slice(10),
            ),
          );
          if (chunk === 2) controller.close();
        },
      }),
      {
        headers: {
          "Content-Type": "text/x.gcode",
          "Content-Length": String(Buffer.byteLength(gcode)),
        },
      },
    );
  });
  const result = await slice({
    ...paths,
    onStatus: (job) => states.push(job.status),
  });
  assert.equal(await readFile(paths.outputPath, "utf8"), gcode);
  assert.equal(result.id, "job-123");
  assert.equal(result.bytes, Buffer.byteLength(gcode));
  assert.equal(
    result.sha256,
    "f1b60c6f4da626ef59157bf734473123e11604035a38af841db6cf5984f36205",
  );
  assert.deepEqual(states, ["queued", "succeeded"]);
});

test("creates or reuses a configuration handle without changing the raw STL or feedback", async (t) => {
  const paths = await fixture(t);
  const configurationPath = join(paths.inputPath, "..", "configuration.json");
  const configuration = {
    printer: {
      profile: { vendor: "BBL", name: "Bambu Lab A1 mini 0.6 nozzle" },
    },
    process: { settings: { layer_height: "0.30" } },
    filament: { settings: { filament_type: ["PLA"] } },
    bed_type: "Textured PEI Plate",
  };
  await writeFile(configurationPath, JSON.stringify(configuration));
  const id = "89abcdef".repeat(8);
  const feedback = {
    fields: [{ key: "nozzle_diameter", result: "loaded_value_matches" }],
    physical_safety: "not_assessed",
  };
  const requests = [];
  t.mock.method(globalThis, "fetch", async (url, options) => {
    requests.push(url.pathname);
    assert.equal(url.origin, "https://orca.bagelindustries.com");
    assert.equal(options.headers.Authorization, "Bearer test-key");
    if (url.pathname === "/v2/configurations") {
      assert.equal(options.headers["Content-Type"], "application/json");
      assert.deepEqual(JSON.parse(options.body), configuration);
      return Response.json({ id }, { status: 201 });
    }
    if (url.pathname === "/v2/jobs") {
      assert.equal(url.search, `?configuration=${id}`);
      assert.equal(options.headers["Content-Type"], "model/stl");
      assert.deepEqual(options.body, await readFile(paths.inputPath));
      return Response.json(
        { id: "configured-job", status: "queued" },
        { status: 202 },
      );
    }
    if (url.pathname === "/v1/jobs/configured-job") {
      return Response.json({
        id: "configured-job",
        status: "succeeded",
        feedback,
      });
    }
    assert.equal(url.pathname, "/v1/jobs/configured-job/gcode");
    return new Response("G1 X12 Y7 E0.4\n", {
      headers: { "Content-Type": "text/x.gcode" },
    });
  });
  const created = await slice({ ...paths, configurationPath });
  assert.deepEqual(created.feedback, feedback);
  const reused = await slice({
    ...paths,
    outputPath: `${paths.outputPath}.reused`,
    configurationId: id,
  });
  assert.deepEqual(reused.feedback, feedback);
  assert.equal(
    requests.filter((path) => path === "/v2/configurations").length,
    1,
  );
  assert.equal(requests.filter((path) => path === "/v2/jobs").length, 2);
  await assert.rejects(
    slice({ ...paths, configurationId: id, preset: "fixed" }),
    /Choose one/,
  );
});

test("preserves an existing output file", async (t) => {
  const paths = await fixture(t);
  await writeFile(paths.outputPath, "existing output");
  t.mock.method(globalThis, "fetch", async (_url, options) =>
    options.method === "POST"
      ? Response.json({ id: "job-456", status: "succeeded" }, { status: 202 })
      : new Response("new output", {
          headers: { "Content-Type": "text/x.gcode" },
        }),
  );
  await assert.rejects(slice(paths), { code: "EEXIST" });
  assert.equal(await readFile(paths.outputPath, "utf8"), "existing output");
});

test("rejects HTTP errors and failed slicing without leaving a G-code file", async (t) => {
  const paths = await fixture(t);
  const fetchMock = t.mock.method(
    globalThis,
    "fetch",
    async () => new Response(null, { status: 401 }),
  );
  await assert.rejects(slice(paths), /HTTP 401/);
  const details = {
    error: "Configuration rejected",
    issues: [{ path: "process.layer_height", code: "out_of_range" }],
  };
  fetchMock.mock.mockImplementation(async () =>
    Response.json(details, { status: 422 }),
  );
  await assert.rejects(slice(paths), { httpStatus: 422, details });
  const configurationId = "12345678".repeat(8);
  await assert.rejects(slice({ ...paths, configurationId }), {
    httpStatus: 422,
    details,
    configurationId,
  });
  const failedJob = {
    id: "job-failed",
    status: "failed",
    error: "Requested settings were not applied",
    verification: { passed: false, mismatches: ["nozzle_diameter"] },
  };
  fetchMock.mock.mockImplementation(async () =>
    Response.json(failedJob, { status: 202 }),
  );
  await assert.rejects(slice(paths), {
    message: "Job job-failed did not succeed (failed).",
    job: failedJob,
  });
  fetchMock.mock.mockImplementation(async () =>
    Response.json({ id: "unexpected-success", status: "succeeded" }),
  );
  const before = fetchMock.mock.callCount();
  await assert.rejects(slice(paths), {
    httpStatus: 200,
    details: { id: "unexpected-success", status: "succeeded" },
  });
  assert.equal(fetchMock.mock.callCount() - before, 1);
  await assert.rejects(readFile(paths.outputPath), { code: "ENOENT" });
});

test("retains the accepted job ID after a polling network failure", async (t) => {
  const paths = await fixture(t);
  t.mock.method(globalThis, "fetch", async (_url, options) => {
    if (options.method === "POST")
      return Response.json(
        { id: "accepted-job", status: "queued" },
        { status: 202 },
      );
    throw new Error("network unavailable");
  });
  await assert.rejects(slice(paths), {
    message: "network unavailable",
    jobId: "accepted-job",
    statusUrl: "https://orca.bagelindustries.com/v1/jobs/accepted-job",
  });
});

test("does not publish empty, partial, wrong-type, or wrong-length downloads", async (t) => {
  const paths = await fixture(t);
  const downloads = [
    new Response("", { headers: { "Content-Type": "text/x.gcode" } }),
    new Response("G1 X1", {
      status: 206,
      headers: { "Content-Type": "text/x.gcode" },
    }),
    Response.json({ error: "not G-code" }),
    new Response("G1 X1", {
      headers: { "Content-Type": "text/x.gcode", "Content-Length": "100" },
    }),
  ];
  const fetchMock = t.mock.method(globalThis, "fetch");
  for (const download of downloads) {
    fetchMock.mock.mockImplementation(async (_url, options) =>
      options.method === "POST"
        ? Response.json(
            { id: "bad-download", status: "succeeded" },
            { status: 202 },
          )
        : download,
    );
    await assert.rejects(slice(paths), { jobId: "bad-download" });
    await assert.rejects(readFile(paths.outputPath), { code: "ENOENT" });
  }
});

test("rejects G-code that differs from the server's completed artifact digest", async (t) => {
  const paths = await fixture(t);
  t.mock.method(globalThis, "fetch", async (_url, options) =>
    options.method === "POST"
      ? Response.json(
          {
            id: "changed-output",
            status: "succeeded",
            output_sha256:
              "f1b60c6f4da626ef59157bf734473123e11604035a38af841db6cf5984f36205",
          },
          { status: 202 },
        )
      : new Response("; generated by OrcaSlicer\nG1 X99 Y7 E0.4\n", {
          headers: { "Content-Type": "text/x.gcode" },
        }),
  );
  await assert.rejects(slice(paths), /does not match the completed job/);
  await assert.rejects(readFile(paths.outputPath), { code: "ENOENT" });
});
